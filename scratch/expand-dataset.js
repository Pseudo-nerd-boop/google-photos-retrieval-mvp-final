// Helper to generate SVG files for new photos
function generateSvg(photo) {
  const bgColors = {
    photo: ['#0284c7', '#0369a1'],
    screenshot: ['#1e293b', '#334155'],
    document: ['#0f766e', '#115e59']
  };

  const icons = {
    photo: '📷',
    screenshot: '📱',
    document: '📄'
  };

  const colors = bgColors[photo.category] || ['#3b82f6', '#1d4ed8'];
  const icon = icons[photo.category] || '🖼️';

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="100%" height="100%">
  <defs>
    <linearGradient id="bg-${photo.id}" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="${colors[0]}" />
      <stop offset="100%" stop-color="${colors[1]}" />
    </linearGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="120%">
      <feDropShadow dx="0" dy="4" stdDeviation="8" flood-opacity="0.3"/>
    </filter>
  </defs>

  <!-- Background -->
  <rect width="800" height="600" fill="url(#bg-${photo.id})" />

  <!-- Visual Card Content -->
  <g filter="url(#shadow)">
    <rect x="60" y="60" width="680" height="480" rx="16" fill="#ffffff" fill-opacity="0.95" stroke="#ffffff" stroke-opacity="0.3" stroke-width="2" />

    <!-- Icon/Illustration Center -->
    <text x="400" y="240" font-family="sans-serif" font-size="64" text-anchor="middle" fill="#1e293b">${icon}</text>

    <!-- Title / Content -->
    <text x="400" y="320" font-family="sans-serif" font-size="24" font-weight="bold" text-anchor="middle" fill="#0f172a">${photo.title.replace(/&/g, '&amp;')}</text>

    <!-- Subtitle Category Badge -->
    <rect x="330" y="350" width="140" height="32" rx="16" fill="${photo.category === 'photo' ? '#0284c7' : photo.category === 'screenshot' ? '#3b82f6' : '#0d9488'}" />
    <text x="400" y="371" font-family="sans-serif" font-size="14" font-weight="bold" text-anchor="middle" fill="#ffffff">${photo.category.toUpperCase()}</text>

    <!-- Location & Date -->
    <text x="400" y="420" font-family="sans-serif" font-size="16" font-weight="600" text-anchor="middle" fill="#475569">📍 ${photo.location.city} | 🗓️ ${photo.date}</text>

    <!-- Tags Footer -->
    <text x="400" y="460" font-family="sans-serif" font-size="14" text-anchor="middle" fill="#64748b">Tags: ${photo.visual_tags.slice(0, 4).join(', ')}</text>
  </g>

  <!-- ID Badge Header -->
  <rect x="80" y="80" width="110" height="30" rx="6" fill="#0f172a" />
  <text x="135" y="100" font-family="monospace" font-size="14" font-weight="bold" text-anchor="middle" fill="#ffffff">${photo.id}</text>
</svg>`;
}

